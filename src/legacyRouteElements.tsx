import { lazy } from "react";

/**
 * Registro leve para as 477 rotas legadas.
 *
 * A árvore de rotas do TanStack importa centenas de arquivos estaticamente;
 * importar todo o catálogo legado nesse ponto avaliava seus wrappers e a
 * tabela de imports em TODA página, mesmo nas rotas comerciais independentes.
 *
 * O componente de cada rota só carrega o catálogo original quando a rota é
 * efetivamente renderizada. O SSR continua dentro do mesmo Suspense e mantém
 * o JsonLdSsrSink no módulo original, após a página resolvida.
 */
const lazyLegacyRoute = (path: string) => {
  let Page: ReturnType<typeof lazy> | undefined;
  return function LegacyRoute() {
    Page ??= lazy(() =>
      import("./legacyRouteElements.impl").then(({ legacyRouteElements }) => {
        const Component = legacyRouteElements[path];
        if (!Component) throw new Error(`Rota legada ausente: ${path}`);
        return { default: Component };
      }),
    );
    return <Page />;
  };
};

